"""Workloads of the determinism matrix (docs/DETERMINISM_MATRIX.md, issue #141).

Committed outputs (deterministic; no randomness here, the C driver seeds its command streams):
  tests/determinism/sixdof.{capsule,lir}.json   IR 0.3, q32-heavy 6DOF: torque/thrust commands, quat_integrate,
                                                quat_rotate, v3_clamp_len, and a probe block (mul, div, sqrt, rsqrt,
                                                v3_len/normalize/cross/dot, quat_normalize/mul, i64/i32 wrap,
                                                shifts, conversions) fed with saturation-edge operands
  tests/determinism/churn.{capsule,lir}.json    IR 0.3 with despawn_self and emit_event (entity churn)
  tests/determinism/rts/*.capsule.json          the four RTS IR systems of capsules/rts with the schedule edges to
                                                the native operators (rts.spatial, rts.scatter) removed: those
                                                operators are not part of the host API (src/host/su_host_operators.c)

    python3 -I tests/determinism/gen_workloads.py           write the committed files
    python3 -I tests/determinism/gen_workloads.py --check   exit 1 when a committed file differs
    python3 -I tests/determinism/gen_workloads.py fixtures --out DIR
        write DIR/rts_duel16.json and DIR/rts_mixed1024.json: the committed RTS scenes duel16 and mixed-1024
        (bench/rts/scenes.lock.json, regenerated by bench/rts/gen/rtsgen.py and checked against the locked scene
        digest) as host world fixtures restricted to the fields the four RTS IR systems bind
"""
