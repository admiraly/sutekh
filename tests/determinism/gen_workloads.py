def gen_sixdof():
    p = Prog()
    dt = p.q(1, 120)
    zero = p.q(0)
    wmax = p.q(8)
    kind = p.op("load_u32", field="kind")
    active = p.op("eq_u32", a=kind, b=p.u(1))
    pos = p.op("load_v3", x="pos_x", y="pos_y", z="pos_z")
    vel = p.op("load_v3", x="vel_x", y="vel_y", z="vel_z")
    rw = p.op("load_q32", field="rot_w")
    rv = p.op("load_v3", x="rot_x", y="rot_y", z="rot_z")
    rot = p.op("make_quat", w=rw, v=rv)
    angvel = p.op("load_v3", x="angvel_x", y="angvel_y", z="angvel_z")
    thrust = p.op("load_v3", x="thrust_x", y="thrust_y", z="thrust_z")
    torque = p.op("load_v3", x="torque_x", y="torque_y", z="torque_z")
    vmax = p.op("load_q32", field="vmax")

    # Rigid body step: body-frame angular velocity, first-order quaternion update, thrust rotated to world.
    w1 = p.op("v3_add", a=angvel, b=p.op("v3_scale", v=torque, s=dt))
    w1 = p.op("v3_clamp_len", v=w1, max=wmax)
    q1 = p.op("quat_integrate", q=rot, w=w1, dt=dt)
    fw = p.op("quat_rotate", q=q1, v=thrust)
    v1 = p.op("v3_add", a=vel, b=p.op("v3_scale", v=fw, s=dt))
    v1 = p.op("v3_clamp_len", v=v1, max=vmax)
    p1 = p.op("v3_add", a=pos, b=p.op("v3_scale", v=v1, s=dt))
    q1 = p.op("select_quat", cond=active, on_true=q1, on_false=rot)
    w1 = p.op("select_v3", cond=active, on_true=w1, on_false=angvel)
    v1 = p.op("select_v3", cond=active, on_true=v1, on_false=vel)
    p1 = p.op("select_v3", cond=active, on_true=p1, on_false=pos)
    p.op("store_v3", x="pos_x", y="pos_y", z="pos_z", src=p1)
    p.op("store_v3", x="vel_x", y="vel_y", z="vel_z", src=v1)
    p.op("store_v3", x="angvel_x", y="angvel_y", z="angvel_z", src=w1)
    p.op("store_q32", field="rot_w", src=p.op("quat_get", q=q1, axis=0))
    p.op("store_v3", x="rot_x", y="rot_y", z="rot_z",
         src=p.op("make_v3", x=p.op("quat_get", q=q1, axis=1), y=p.op("quat_get", q=q1, axis=2),
                  z=p.op("quat_get", q=q1, axis=3)))

    # Probe block: every result is stored, so a single differing bit anywhere reaches the digest.
    a = p.op("load_q32", field="probe_a")
    b = p.op("load_q32", field="probe_b")
    c = p.op("load_q32", field="probe_c")
    n = p.op("load_u32", field="probe_n")
    p.op("store_q32", field="o_mul", src=p.op("mul_q32", a=a, b=b))
    p.op("store_q32", field="o_div", src=p.op("div_q32", a=a, b=b))
    p.op("store_q32", field="o_sqrt", src=p.op("sqrt_q32", a=a))
    p.op("store_q32", field="o_rsqrt", src=p.op("rsqrt_q32", a=b))
    pv = p.op("make_v3", x=a, y=b, z=c)
    p.op("store_q32", field="o_len", src=p.op("v3_len", a=pv))
    p.op("store_q32", field="o_dot", src=p.op("v3_dot", a=pv, b=v1))
    p.op("store_q32", field="o_lensq", src=p.op("v3_len_sq", a=pv))
    p.op("store_v3", x="o_nx", y="o_ny", z="o_nz", src=p.op("v3_normalize", a=pv))
    p.op("store_v3", x="o_cx", y="o_cy", z="o_cz", src=p.op("v3_cross", a=pv, b=p1))
    p.op("store_v3", x="o_rx", y="o_ry", z="o_rz", src=p.op("quat_rotate", q=q1, v=pv))
    qp = p.op("quat_normalize", a=p.op("make_quat", w=c, v=pv))
    qm = p.op("quat_mul", a=qp, b=p.op("quat_conj", a=q1))
    p.op("store_q32", field="o_qw", src=p.op("quat_get", q=qm, axis=0))
    p.op("store_v3", x="o_qx", y="o_qy", z="o_qz",
         src=p.op("make_v3", x=p.op("quat_get", q=qm, axis=1), y=p.op("quat_get", q=qm, axis=2),
                  z=p.op("quat_get", q=qm, axis=3)))
    # Integration of an unnormalized probe quaternion (saturation inside quat_mul and the normalize).
    qk = p.op("quat_integrate", q=p.op("make_quat", w=a, v=p.op("make_v3", x=b, y=c, z=a)), w=pv, dt=c)
    p.op("store_v3", x="o_kx", y="o_ky", z="o_kz",
         src=p.op("make_v3", x=p.op("quat_get", q=qk, axis=0), y=p.op("quat_get", q=qk, axis=1),
                  z=p.op("quat_get", q=qk, axis=3)))
    ra = p.op("q32_raw", a=a)
    rb = p.op("q32_raw", a=b)
    p.op("store_i64", field="o_i64", src=p.op("add_i64", a=p.op("mul_i64", a=ra, b=rb), b=p.op("neg_i64", a=ra)))
    p.op("store_i64", field="o_idiv", src=p.op("div_i64", a=ra, b=rb))
    ia = p.op("i32_from_i64", a=ra)
    ib = p.op("i32_from_i64", a=rb)
    p.op("store_i32", field="o_i32", src=p.op("sub_i32", a=p.op("mul_i32", a=ia, b=ib), b=p.op("div_i32", a=ia, b=ib)))
    p.op("store_i32", field="o_round", src=p.op("q32_to_i32_round", a=a))
    p.op("store_i64", field="o_floor", src=p.op("q32_to_i64_floor", a=b))
    p.op("store_q32", field="o_shl", src=p.op("shl_q32", a=a, n=n))
    p.op("store_q32", field="o_shr", src=p.op("shr_q32", a=b, n=n))
    p.op("store_i64", field="o_shl64", src=p.op("shr_i64", a=p.op("shl_i64", a=rb, n=n), n=p.op("sub_u32", a=n, b=p.u(3))))
    p.op("store_q32", field="o_conv",
         src=p.op("add_q32", a=p.op("q32_from_i64", a=p.op("shr_i64", a=ra, n=p.u(20))),
                  b=p.op("q32_from_i32", a=p.op("q32_to_i32_floor", a=c))))
    p.op("store_q32", field="o_clamp", src=p.op("clamp_q32", x=a, lo=p.op("neg_q32", a=p.op("abs_q32", a=b)), hi=c))
    p.op("store_q32", field="o_mm",
         src=p.op("sub_q32", a=p.op("max_q32", a=a, b=b), b=p.op("min_q32", a=p.op("abs_q32", a=c), b=zero)))
    fields = sorted(SIX, key=lambda k: SIX[k][0])
    cap = capsule03("det.sixdof", "sixdof.lir.json", "det.sixdof", SIX, fields, SIX_READ_ONLY)
    return cap, lir03("det.sixdof", "det.sixdof", p.ins)


