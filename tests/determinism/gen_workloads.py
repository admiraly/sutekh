SIX_READ_ONLY = {"kind", "probe_n", "thrust_x", "thrust_y", "thrust_z", "torque_x", "torque_y", "torque_z", "vmax",
                 "probe_a", "probe_b", "probe_c"}


def gen_sixdof():
    p = Prog()
    dt = p.q(1, 120)
    zero = p.q(0)
    wmax = p.q(8)
    kind = p.op("load_u32", field="kind")
    active = p.op("eq_u32", a=kind, b=p.u(1))
    pos = p.op("load_v3", x="pos_x", y="pos_y", z="pos_z")
    vel = p.op("load_v3", x="vel_x", y="vel_y", z="vel_z")
    rw = p.op("load_q32", field="rot_w")
    rv = p.op("load_v3", x="rot_x", y="rot_y", z="rot_z")
    rot = p.op("make_quat", w=rw, v=rv)
    angvel = p.op("load_v3", x="angvel_x", y="angvel_y", z="angvel_z")
    thrust = p.op("load_v3", x="thrust_x", y="thrust_y", z="thrust_z")
    torque = p.op("load_v3", x="torque_x", y="torque_y", z="torque_z")
    vmax = p.op("load_q32", field="vmax")

    # Rigid body step: body-frame angular velocity, first-order quaternion update, thrust rotated to world.
    w1 = p.op("v3_add", a=angvel, b=p.op("v3_scale", v=torque, s=dt))
    w1 = p.op("v3_clamp_len", v=w1, max=wmax)
    q1 = p.op("quat_integrate", q=rot, w=w1, dt=dt)
    fw = p.op("quat_rotate", q=q1, v=thrust)
    v1 = p.op("v3_add", a=vel, b=p.op("v3_scale", v=fw, s=dt))
    v1 = p.op("v3_clamp_len", v=v1, max=vmax)
    p1 = p.op("v3_add", a=pos, b=p.op("v3_scale", v=v1, s=dt))
    q1 = p.op("select_quat", cond=active, on_true=q1, on_false=rot)
    w1 = p.op("select_v3", cond=active, on_true=w1, on_false=angvel)
    v1 = p.op("select_v3", cond=active, on_true=v1, on_false=vel)
    p1 = p.op("select_v3", cond=active, on_true=p1, on_false=pos)
    p.op("store_v3", x="pos_x", y="pos_y", z="pos_z", src=p1)
    p.op("store_v3", x="vel_x", y="vel_y", z="vel_z", src=v1)
    p.op("store_v3", x="angvel_x", y="angvel_y", z="angvel_z", src=w1)
    p.op("store_q32", field="rot_w", src=p.op("quat_get", q=q1, axis=0))
    p.op("store_v3", x="rot_x", y="rot_y", z="rot_z",
         src=p.op("make_v3", x=p.op("quat_get", q=q1, axis=1), y=p.op("quat_get", q=q1, axis=2),
                  z=p.op("quat_get", q=q1, axis=3)))

    # Probe block: every result is stored, so a single differing bit anywhere reaches the digest.
    a = p.op("load_q32", field="probe_a")
    b = p.op("load_q32", field="probe_b")
    c = p.op("load_q32", field="probe_c")
    n = p.op("load_u32", field="probe_n")
    p.op("store_q32", field="o_mul", src=p.op("mul_q32", a=a, b=b))
    p.op("store_q32", field="o_div", src=p.op("div_q32", a=a, b=b))
    p.op("store_q32", field="o_sqrt", src=p.op("sqrt_q32", a=a))
    p.op("store_q32", field="o_rsqrt", src=p.op("rsqrt_q32", a=b))
    pv = p.op("make_v3", x=a, y=b, z=c)
    p.op("store_q32", field="o_len", src=p.op("v3_len", a=pv))
    p.op("store_q32", field="o_dot", src=p.op("v3_dot", a=pv, b=v1))
    p.op("store_q32", field="o_lensq", src=p.op("v3_len_sq", a=pv))
    p.op("store_v3", x="o_nx", y="o_ny", z="o_nz", src=p.op("v3_normalize", a=pv))
    p.op("store_v3", x="o_cx", y="o_cy", z="o_cz", src=p.op("v3_cross", a=pv, b=p1))
    p.op("store_v3", x="o_rx", y="o_ry", z="o_rz", src=p.op("quat_rotate", q=q1, v=pv))
    qp = p.op("quat_normalize", a=p.op("make_quat", w=c, v=pv))
    qm = p.op("quat_mul", a=qp, b=p.op("quat_conj", a=q1))
    p.op("store_q32", field="o_qw", src=p.op("quat_get", q=qm, axis=0))
    p.op("store_v3", x="o_qx", y="o_qy", z="o_qz",
         src=p.op("make_v3", x=p.op("quat_get", q=qm, axis=1), y=p.op("quat_get", q=qm, axis=2),
                  z=p.op("quat_get", q=qm, axis=3)))
    # Integration of an unnormalized probe quaternion (saturation inside quat_mul and the normalize).
    qk = p.op("quat_integrate", q=p.op("make_quat", w=a, v=p.op("make_v3", x=b, y=c, z=a)), w=pv, dt=c)
    p.op("store_v3", x="o_kx", y="o_ky", z="o_kz",
         src=p.op("make_v3", x=p.op("quat_get", q=qk, axis=0), y=p.op("quat_get", q=qk, axis=1),
                  z=p.op("quat_get", q=qk, axis=3)))
    ra = p.op("q32_raw", a=a)
    rb = p.op("q32_raw", a=b)
    p.op("store_i64", field="o_i64", src=p.op("add_i64", a=p.op("mul_i64", a=ra, b=rb), b=p.op("neg_i64", a=ra)))
    p.op("store_i64", field="o_idiv", src=p.op("div_i64", a=ra, b=rb))
    ia = p.op("i32_from_i64", a=ra)
    ib = p.op("i32_from_i64", a=rb)
    p.op("store_i32", field="o_i32", src=p.op("sub_i32", a=p.op("mul_i32", a=ia, b=ib), b=p.op("div_i32", a=ia, b=ib)))
    p.op("store_i32", field="o_round", src=p.op("q32_to_i32_round", a=a))
    p.op("store_i64", field="o_floor", src=p.op("q32_to_i64_floor", a=b))
    p.op("store_q32", field="o_shl", src=p.op("shl_q32", a=a, n=n))
    p.op("store_q32", field="o_shr", src=p.op("shr_q32", a=b, n=n))
    p.op("store_i64", field="o_shl64", src=p.op("shr_i64", a=p.op("shl_i64", a=rb, n=n), n=p.op("sub_u32", a=n, b=p.u(3))))
    p.op("store_q32", field="o_conv",
         src=p.op("add_q32", a=p.op("q32_from_i64", a=p.op("shr_i64", a=ra, n=p.u(20))),
                  b=p.op("q32_from_i32", a=p.op("q32_to_i32_floor", a=c))))
    p.op("store_q32", field="o_clamp", src=p.op("clamp_q32", x=a, lo=p.op("neg_q32", a=p.op("abs_q32", a=b)), hi=c))
    p.op("store_q32", field="o_mm",
         src=p.op("sub_q32", a=p.op("max_q32", a=a, b=b), b=p.op("min_q32", a=p.op("abs_q32", a=c), b=zero)))
    fields = sorted(SIX, key=lambda k: SIX[k][0])
    cap = capsule03("det.sixdof", "sixdof.lir.json", "det.sixdof", SIX, fields, SIX_READ_ONLY)
    return cap, lir03("det.sixdof", "det.sixdof", p.ins)


# ---------------------------------------------------------------------------------------------------------------
# churn: q32 motion, energy drain, despawn_self and emit_event (the host spawns and despawns around it)
# ---------------------------------------------------------------------------------------------------------------

CHURN = {
    "kind": (1, "u32"), "life": (2, "u32"),
    "energy": (4, "q32"), "drain": (6, "q32"),
    "pos_x": (8, "q32"), "pos_y": (10, "q32"), "pos_z": (12, "q32"),
    "vel_x": (14, "q32"), "vel_y": (16, "q32"), "vel_z": (18, "q32"),
    "score": (20, "i64"),
}


def gen_churn():
    p = Prog()
    dt = p.q(1, 60)
    damp = p.q(255, 256)
    zero = p.q(0)
    life = p.op("load_u32", field="life")
    energy = p.op("load_q32", field="energy")
    drain = p.op("load_q32", field="drain")
    pos = p.op("load_v3", x="pos_x", y="pos_y", z="pos_z")
    vel = p.op("load_v3", x="vel_x", y="vel_y", z="vel_z")
    score = p.op("load_i64", field="score")
    e1 = p.op("sub_q32", a=energy, b=drain)
    l1 = p.op("sub_u32", a=life, b=p.u(1))
    p1 = p.op("v3_add", a=pos, b=p.op("v3_scale", v=vel, s=dt))
    v1 = p.op("v3_scale", v=vel, s=damp)
    s1 = p.op("add_i64", a=score, b=p.op("q32_to_i64_floor", a=p.op("v3_len", a=p1)))
    die = p.op("or_bool", a=p.op("le_q32", a=e1, b=zero), b=p.op("eq_u32", a=life, b=p.u(0)))
    slot = p.op("slot_u32")
    tick = p.op("tick_u32")
    gen = p.op("gen_u32")
    dist = p.op("u32_from_i32", a=p.op("q32_to_i32_round", a=p.op("v3_len", a=p1)))
    p.op("emit_event", cond=die, kind=3, a=slot, b=dist)
    ping = p.op("and_bool", a=p.op("not_bool", a=die),
                b=p.op("eq_u32", a=p.op("mul_u32", a=tick, b=p.u(1 << 28)), b=p.op("mul_u32", a=slot, b=p.u(1 << 28))))
    # (x * 2^28 mod 2^32 keeps the low 4 bits: tick mod 16 == slot mod 16 without the IR 0.4 bit operations.)
    p.op("emit_event", cond=ping, kind=4, a=gen, b=l1)
    p.op("despawn_self", cond=die)
    p.op("store_u32", field="life", src=l1)
    p.op("store_q32", field="energy", src=e1)
    p.op("store_v3", x="pos_x", y="pos_y", z="pos_z", src=p1)
    p.op("store_v3", x="vel_x", y="vel_y", z="vel_z", src=v1)
    p.op("store_i64", field="score", src=s1)
    fields = sorted(CHURN, key=lambda k: CHURN[k][0])
    cap = capsule03("det.churn", "churn.lir.json", "det.churn", CHURN, fields, {"kind", "drain"},
                    caps=["despawn_self", "emit_event"], limits={"max_struct_per_row": 1, "max_events_per_row": 2})
    return cap, lir03("det.churn", "det.churn", p.ins)


# ---------------------------------------------------------------------------------------------------------------
# RTS IR systems without the native operators
# ---------------------------------------------------------------------------------------------------------------

RTS_SYSTEMS = ("damage", "goal", "combat", "move")  # schedule order of the matrix world (see det_matrix.c)
RTS_PRESENT = {"rts." + s for s in RTS_SYSTEMS}


def derived_rts(name):
    with open(os.path.join(ROOT, "capsules", "rts", name + ".capsule.json"), encoding="utf-8") as f:
        c = json.load(f)
    s = c["schedule"]
    s["after"] = [x for x in s["after"] if x in RTS_PRESENT]
    s["before"] = [x for x in s["before"] if x in RTS_PRESENT]
    # damage reads incoming before combat zeroes it: the host stands in for rts.scatter between ticks.
    if name == "damage":
        s["before"] = ["rts.combat"]
    if name == "combat":
        s["after"] = [x for x in s["after"] if x != "rts.damage"]
    c["source"] = "../../../capsules/rts/%s.lir.json" % name
    c["tests"] = ["tests/determinism/det_matrix.c"]
    return c


def outputs():
    six_c, six_l = gen_sixdof()
    ch_c, ch_l = gen_churn()
    out = {
        "tests/determinism/sixdof.capsule.json": six_c, "tests/determinism/sixdof.lir.json": six_l,
        "tests/determinism/churn.capsule.json": ch_c, "tests/determinism/churn.lir.json": ch_l,
    }
    for s in RTS_SYSTEMS:
        out["tests/determinism/rts/%s.capsule.json" % s] = derived_rts(s)
    return out


# ---------------------------------------------------------------------------------------------------------------
# RTS scene fixtures (generated at test time from the locked scenes)
# ---------------------------------------------------------------------------------------------------------------

RTS_SCENES = (("duel16", "rts_duel16.json"), ("mixed-1024", "rts_mixed1024.json"))


def rts_fields():
    names = set()
    for s in RTS_SYSTEMS:
        with open(os.path.join(ROOT, "capsules", "rts", s + ".capsule.json"), encoding="utf-8") as f:
            for fd in json.load(f)["fields"]:
                names.add(fd["name"])
    return names


def write_fixtures(out_dir):
    import rtsgen  # noqa: E402  (bench/rts/gen)
    profile = rtsgen.load_profile()
    with open(rtsgen.LOCK_PATH, encoding="utf-8") as f:
        lock = {s["name"]: s for s in json.load(f)["scenes"]}
    names = rts_fields()
    os.makedirs(out_dir, exist_ok=True)
    for scene, fname in RTS_SCENES:
        spec = lock[scene]
        arr, _params, digest = rtsgen.make_scene(profile, spec)
        if "sha256:" + digest != spec["scene_digest"]:
            print("scene %s: digest %s differs from the lock %s" % (scene, digest, spec["scene_digest"]), file=sys.stderr)
            return 1
        rows = len(arr) // rtsgen.FIELD_COUNT
        cols = {}
        for name in rtsgen.FIELD_NAMES:
            if name in names:
                ix = rtsgen.IX[name]
                cols[name] = [arr[r * rtsgen.FIELD_COUNT + ix] for r in range(rows)]
        # Constant scene columns the IR systems do not bind (inputs of the operators the host stands in for): the
        # driver reads them from this side table, one row per line.
        side_cols = ("team", "kind", "range_sq", "formation_slot", "formation_gen")
        fx = {"schema_id": "rts", "tick": 0, "entity_ids": list(range(1, rows + 1)), "columns": cols}
        with open(os.path.join(out_dir, fname), "w", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(fx, separators=(",", ":")) + "\n")
        with open(os.path.join(out_dir, fname.replace(".json", ".side.txt")), "w", encoding="utf-8",
                  newline="\n") as f:
            f.write("%d\n" % rows)
            for r in range(rows):
                f.write(" ".join(str(arr[r * rtsgen.FIELD_COUNT + rtsgen.IX[n]]) for n in side_cols) + "\n")
        print("%s: %d rows, scene digest %s (locked)" % (fname, rows, digest))
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", nargs="?", default="write", choices=("write", "fixtures"))
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out")
    args = ap.parse_args()
    if args.mode == "fixtures":
        if not args.out:
            ap.error("fixtures needs --out")
        return write_fixtures(args.out)
    bad = 0
    for rel, obj in outputs().items():
        text = json.dumps(obj, indent=1) + "\n"
        path = os.path.join(ROOT, rel)
        if args.check:
            try:
                with open(path, encoding="utf-8", newline="") as f:
                    cur = f.read()
            except OSError:
                cur = None
            if cur != text:
                print("differs:", rel)
                bad += 1
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    if not args.check:
        o = outputs()
        print("sixdof: %d instructions; churn: %d instructions" % (
            len(o["tests/determinism/sixdof.lir.json"]["instructions"]),
            len(o["tests/determinism/churn.lir.json"]["instructions"])))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
