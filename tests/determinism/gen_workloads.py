# ---------------------------------------------------------------------------------------------------------------
# IR helper (the style of bench/space3d/gen_racer.py)
# ---------------------------------------------------------------------------------------------------------------


class Prog:
    def __init__(self):
        self.ins = []
        self.n = 0

    def op(self, op, **kw):
        if op.startswith("store_") or op in ("emit_event", "despawn_self"):
            self.ins.append(dict(op=op, **kw))
            return None
        self.n += 1
        dst = "r%d" % self.n
        self.ins.append(dict(op=op, dst=dst, **kw))
        return dst

    def q(self, num, den=1):
        return self.op("const_q32", num=num, den=den)

    def u(self, v):
        return self.op("const_u32", value=v)


def capsule03(system_id, src, schema, table, fields, reads_only, caps=None, limits=None):
    out = []
    for name in fields:
        fid, t = table[name]
        out.append({"id": fid, "name": name, "type": t, "read": True, "write": name not in reads_only})
    c = {
        "capsule_format": "0.1", "ir_version": "0.3", "system_id": system_id, "source": src,
        "schema": {"id": schema, "version": 1, "layout_generation": 1}, "numeric_profile": "fixed_q32_v1",
        "fields": out,
        "schedule": {"phase": "simulate", "after": [], "before": [], "parallel": "serial"},
        "limits": {"max_instructions": 4096, "max_rows": 65536, "allocation": "forbidden"},
        "tests": ["tests/determinism/det_matrix.c"],
    }
    if caps is not None:
        c["capabilities"] = caps
    if limits is not None:
        c["limits"].update(limits)
    return c


def lir03(system_id, schema, ins):
    return {"ir_version": "0.3", "system_id": system_id, "numeric_profile": "fixed_q32_v1", "query": schema,
            "instructions": ins}


