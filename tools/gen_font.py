def render():
    lines = [
        "/* Generated by tools/gen_font.py. Do not edit. Project-authored 5x7 glyphs, ASCII 32..126. */",
        "/* SPDX-FileCopyrightText: 2026 admiraly */",
        "/* SPDX-License-Identifier: LicenseRef-PolyForm-Perimeter-1.0.1 */",
        "#ifndef SU_FONT5X7_H",
        "#define SU_FONT5X7_H",
        "",
        "#include <stdint.h>",
        "",
        "/* 7 rows per glyph, bit 4 = leftmost column. */",
        "static const uint8_t su_font5x7[95][7] = {",
    ]
    for code in range(32, 127):
        ch = chr(code)
        rows = GLYPHS[ch]
        if len(rows) != 7 or any(len(r) != 5 or set(r) - {".", "#"} for r in rows):
            raise SystemExit("bad glyph %r" % ch)
        vals = [sum(1 << (4 - i) for i, c in enumerate(r) if c == "#") for r in rows]
        name = "backslash" if ch == "\\" else ("space" if ch == " " else ch)
        lines.append("    {%s}, /* %s */" % (", ".join("0x%02x" % v for v in vals), name.replace("*/", "* /")))
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main(argv):
    text = render()
    if "--check" in argv:
        try:
            with open(OUT, "r", encoding="utf-8") as fh:
                ok = fh.read() == text
        except OSError:
            ok = False
        print("font header %s" % ("ok" if ok else "STALE"))
        return 0 if ok else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote " + os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
