"""Compile the renderer's GLSL shaders offline into embedded SPIR-V (src/render/su_render_shaders.h).

Modes:
  --compiler PATH        compile every src/render/shaders/*.{vert,frag} with glslang (glslangValidator or
                         glslang, run as: PATH -V --target-env vulkan1.2 -o OUT SRC) and rewrite the header
  --check                verify the committed header: every shader source's SHA-256 matches the one recorded
                         in the header (works without a compiler); with --compiler also recompile and require
                         identical SPIR-V words

The header records the compiler's version line and each source's SHA-256, so a stale header is detected.
Stdlib only; subprocesses get argument lists (shell=False).
"""

import argparse
import hashlib
import os
import re
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(ROOT, "src", "render", "shaders")
HEADER = os.path.join(ROOT, "src", "render", "su_render_shaders.h")
SHADERS = ["mesh.vert", "mesh.frag", "line.vert", "line.frag", "pbr.vert", "pbr.frag", "fullscreen.vert", "sky.frag",
           "post.frag", "hud.vert", "hud.frag", "fx.vert", "fx.frag",
"bloom_down.frag", "bloom_up.frag", "post_bloom.frag", "paint.frag"]
# Shared sources pulled in with #include (GL_GOOGLE_include_directive); their hashes are recorded too.
INCLUDES = ["frame.glsl"]


def symbol(name):
    return "su_shader_" + name.replace(".", "_")


def sha256(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def compiler_version(compiler):
    res = subprocess.run([compiler, "--version"], shell=False, capture_output=True, text=True, check=False)
    first = (res.stdout.strip().splitlines() or ["unknown"])[0]
    return first.strip()


def compile_one(compiler, src):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "out.spv")
        res = subprocess.run([compiler, "-V", "--target-env", "vulkan1.2", "-o", out, src], shell=False,
                             capture_output=True, text=True, check=False)
        if res.returncode != 0:
            raise SystemExit("compile failed: %s\n%s%s" % (src, res.stdout, res.stderr))
        with open(out, "rb") as fh:
            data = fh.read()
    if len(data) % 4 != 0 or struct.unpack_from("<I", data, 0)[0] != 0x07230203:
        raise SystemExit("not SPIR-V: " + src)
    return list(struct.unpack("<%dI" % (len(data) // 4), data))


def render_header(version, entries):
    lines = [
        "/* Generated by tools/compile_shaders.py from src/render/shaders. Do not edit. */",
        "/* SPDX-FileCopyrightText: 2026 admiraly */",
        "/* SPDX-License-Identifier: LicenseRef-PolyForm-Perimeter-1.0.1 */",
        "/* compiler: %s; target: vulkan1.2 */" % version,
        "#ifndef SU_RENDER_SHADERS_H",
        "#define SU_RENDER_SHADERS_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    for name in INCLUDES:
        lines.append("/* include %s sha256 %s */" % (name, sha256(os.path.join(SRC_DIR, name))))
    lines.append("")
    for name, digest, words in entries:
        lines.append("/* %s sha256 %s */" % (name, digest))
        lines.append("static const uint32_t %s[%d] = {" % (symbol(name), len(words)))
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join("0x%08xu" % w for w in words[i:i + 8]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def parse_header(text):
    """Returns {name: (sha256, [words])}."""
    out = {}
    for m in re.finditer(r"/\* (\S+) sha256 ([0-9a-f]{64}) \*/\nstatic const uint32_t \w+\[(\d+)\] = \{(.*?)\};",
                         text, re.S):
        words = [int(w.rstrip("u"), 16) for w in re.findall(r"0x[0-9a-f]{8}u", m.group(4))]
        if len(words) != int(m.group(3)):
            raise SystemExit("header array length mismatch for " + m.group(1))
        out[m.group(1)] = (m.group(2), words)
    return out


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--compiler")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    if args.check:
        if not os.path.exists(HEADER):
            print("FAIL: %s missing" % HEADER)
            return 1
        with open(HEADER, "r", encoding="utf-8") as fh:
            recorded = parse_header(fh.read())
        ok = True
        with open(HEADER, "r", encoding="utf-8") as fh:
            text = fh.read()
        for name in INCLUDES:
            m = re.search(r"/\* include %s sha256 ([0-9a-f]{64}) \*/" % re.escape(name), text)
            if m is None or m.group(1) != sha256(os.path.join(SRC_DIR, name)):
                print("FAIL: include %s changed since the header was generated" % name)
                ok = False
        for name in SHADERS:
            digest = sha256(os.path.join(SRC_DIR, name))
            if name not in recorded or recorded[name][0] != digest:
                print("FAIL: %s changed since the header was generated" % name)
                ok = False
            elif args.compiler:
                words = compile_one(args.compiler, os.path.join(SRC_DIR, name))
                if words != recorded[name][1]:
                    print("FAIL: %s compiles to different SPIR-V with %s" % (name, compiler_version(args.compiler)))
                    ok = False
        print("shaders: %s (%d sources, %d includes%s)" % ("ok" if ok else "STALE", len(SHADERS), len(INCLUDES),
                                               ", recompiled" if args.compiler else ", hashes only"))
        return 0 if ok else 1
    if not args.compiler:
        ap.error("--compiler is required to generate the header")
    version = compiler_version(args.compiler)
    entries = []
    for name in SHADERS:
        path = os.path.join(SRC_DIR, name)
        entries.append((name, sha256(path), compile_one(args.compiler, path)))
    with open(HEADER, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render_header(version, entries))
    print("wrote %s (%s)" % (HEADER, version))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
